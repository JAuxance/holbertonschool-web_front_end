def sum_mixed_list(mxd_lst: list) -> float:
    """Returns the sum of all the elements of a list
    Args:
        mxd_lst (list): list of integers and floats to sum
    Returns:
        float: the sum of all the elements of mxd_lst
    """
    return sum(mxd_lst)
